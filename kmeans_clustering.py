import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_blobs
from sklearn.cluster import KMeans
from skimage import data

X, y_true = make_blobs(
    n_samples=1000,
    centers=4,
    random_state=42
)

print("Dataset shape:", X.shape)

plt.figure(figsize=(8, 6))

plt.scatter(X[:, 0], X[:, 1], color="gray")

plt.title("Generated Data Before K-Means")
plt.xlabel("X coordinate")
plt.ylabel("Y coordinate")

plt.savefig("kmeans_data_before.png")
plt.show()

kmeans = KMeans(
    n_clusters=4,
    random_state=42,
    n_init=10
)

labels = kmeans.fit_predict(X)

plt.figure(figsize=(8, 6))

plt.scatter(
    X[:, 0],
    X[:, 1],
    c=labels,
    cmap="viridis"
)
centers = kmeans.cluster_centers_

plt.scatter(
    centers[:, 0],
    centers[:, 1],
    color="red",
    marker="X",
    s=200,
    label="Cluster Centers"
)

plt.title("Generated Data After K-Means")
plt.xlabel("X coordinate")
plt.ylabel("Y coordinate")
plt.legend()

plt.savefig("kmeans_data_after.png")
plt.show()

coffee = data.coffee()

print("Image shape:", coffee.shape)

plt.figure(figsize=(8, 6))
plt.imshow(coffee)
plt.title("Coffee Image Before K-Means")
plt.axis("off")

plt.savefig("kmeans_image_before.png")
plt.show()

height, width, channels = coffee.shape

pixels = coffee.reshape(-1, 3)

print("Original image shape:", coffee.shape)
print("Pixel data shape:", pixels.shape)

image_kmeans = KMeans(
    n_clusters=4,
    random_state=42,
    n_init=10
)

# RGB colors
pixel_labels = image_kmeans.fit_predict(pixels)

# Get the RGB color of each cluster center
cluster_colors = image_kmeans.cluster_centers_

#center's color
new_pixels = cluster_colors[pixel_labels]

# Restore the original image dimensions
coffee_after = new_pixels.reshape(height, width, channels)

# Convert colors back to the image's integer format
coffee_after = np.clip(coffee_after, 0, 255).astype(np.uint8)

plt.figure(figsize=(8, 6))
plt.imshow(coffee_after)
plt.title("Coffee Image After K-Means")
plt.axis("off")

plt.savefig("kmeans_image_after.png")
plt.show()