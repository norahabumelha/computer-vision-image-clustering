import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_circles
from sklearn.cluster import SpectralClustering
from sklearn.cluster import spectral_clustering
from sklearn.feature_extraction import image as sk_image
from skimage import data
from skimage.transform import rescale
from skimage.filters import gaussian

X, y_true = make_circles(
    n_samples=1000,
    factor=0.5,
    noise=0.05,
    random_state=42
)

print("Dataset shape:", X.shape)

plt.figure(figsize=(8, 6))

plt.scatter(X[:, 0], X[:, 1], color="gray")

plt.title("Generated Data Before Spectral Clustering")
plt.xlabel("X coordinate")
plt.ylabel("Y coordinate")

plt.savefig("spectral_data_before.png")
plt.show()
plt.close()

spectral_model = SpectralClustering(
    n_clusters=2,
    affinity="nearest_neighbors",
    random_state=42
)
labels = spectral_model.fit_predict(X)

plt.figure(figsize=(8, 6))

plt.scatter(
    X[:, 0],
    X[:, 1],
    c=labels,
    cmap="viridis"
)

plt.title("Generated Data After Spectral Clustering")
plt.xlabel("X coordinate")
plt.ylabel("Y coordinate")

plt.savefig("spectral_data_after.png")
plt.show()
plt.close()

# coins image
coins = data.coins()

print("Original Image shape:", coins.shape)

plt.figure(figsize=(8, 6))
plt.imshow(coins, cmap="gray")
plt.title("Coins Image Before Spectral Clustering")
plt.axis("off")

plt.savefig("spectral_image_before.png")
plt.show()
plt.close()

smooth_image = gaussian(coins, sigma=2)

small_image = rescale(
    smooth_image,
    0.2,
    anti_aliasing=True
)
print("Resized image shape:", small_image.shape)

# Convert image into a graph

graph = sk_image.img_to_graph(small_image)

# Transform graph weights as required by the lab

graph.data = np.exp(

    -10 * graph.data / graph.data.std()

)

print("Graph shape:", graph.shape)

# Apply Spectral Clustering
labels = spectral_clustering(

    graph,

    n_clusters=25,

    assign_labels="discretize",

    random_state=42

)

# Reshape labels into the image dimensions
clustered_image = labels.reshape(small_image.shape)

plt.figure(figsize=(8, 6))

plt.imshow(clustered_image, cmap="nipy_spectral")

plt.title("Coins Image After Spectral Clustering")

plt.axis("off")

plt.savefig("spectral_image_after.png")

plt.show()

plt.close()

print("Spectral Clustering completed successfully.")

print("Four PNG images have been saved.")